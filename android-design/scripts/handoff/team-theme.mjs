#!/usr/bin/env node
// android-design · team-theme — write the team's Compose theme files from an HTML flow's tokens.
// Usage: node team-theme.mjs <flow-dir> --package <com.x.y> [--out <dir>] [--name BaseCodeTheme] [--scheme light|dark|both] [--force]
// Reads <flow-dir>/tokens.css (+ app.css :root colours). Writes Color.kt, Typography.kt, Font.kt, Dimens.kt, Theme.kt
// in the team's house style (references/house-style.md) and token-map.md (CSS variable → Kotlin name). Existing files
// are never overwritten without --force: the new version is written next to them as *.kt.new.
import fs from 'node:fs';
import path from 'node:path';

const argv = process.argv.slice(2);
const opt = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
const dir = path.resolve(argv.find((a) => !a.startsWith('--') && argv[argv.indexOf(a) - 1]?.startsWith('--') !== true) || '.');
const pkg = opt('--package');
if (!pkg) { console.error('--package <com.example.app> is required (the theme files go to <package>.presentation.utils.theme)'); process.exit(1); }
const out = path.resolve(opt('--out', path.join(dir, 'handoff', 'theme')));
const themeName = opt('--name', 'BaseCodeTheme');
const force = argv.includes('--force');

const tokens = fs.readFileSync(path.join(dir, 'tokens.css'), 'utf8');
const appCss = fs.existsSync(path.join(dir, 'app.css')) ? fs.readFileSync(path.join(dir, 'app.css'), 'utf8') : '';
const block = (css, sel) => { const m = new RegExp(sel.replace(/[[\]()=".]/g, '\\$&') + '\\s*\\{([^}]*)\\}').exec(css); return m ? m[1] : ''; };
const vars = (body) => Object.fromEntries([...body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const light = vars(block(tokens, ':root'));
const dark = vars(block(tokens, ':root[data-theme="dark"]'));
const appVars = vars(block(appCss, ':root'));

// scheme: explicit, else dark if most screens are authored dark-first
let scheme = opt('--scheme');
if (!scheme) {
  const scr = path.join(dir, 'screens');
  const htmls = fs.existsSync(scr) ? fs.readdirSync(scr).filter((f) => f.endsWith('.html')).map((f) => fs.readFileSync(path.join(scr, f), 'utf8')) : [];
  const darkFirst = htmls.filter((h) => /<html[^>]*data-theme="dark"/.test(h)).length > htmls.length / 2;
  scheme = darkFirst ? 'dark' : 'light';
}

const pascal = (s) => s.split('-').map((w) => (w ? w[0].toUpperCase() + w.slice(1) : '')).join('');
const isHex = (v) => /^#([0-9a-f]{6}|[0-9a-f]{8})$/i.test(v);
const kColor = (v) => { const h = v.slice(1).toUpperCase(); return `Color(0x${h.length === 6 ? 'FF' + h : h.slice(6) + h.slice(0, 6)})`; };
const nameOf = (k) => (k.startsWith('md-') ? 'Md' + pascal(k.slice(3)) : k.startsWith('x-') ? pascal(k.slice(2)) : pascal(k));

// ---------- Color.kt ----------
const map = [];
const colorLines = (src, suffix, label) => {
  const rows = [`// ${label}`];
  for (const [k, v] of Object.entries(src)) {
    if (!isHex(v) || !/^(md-|x-)/.test(k)) continue;
    const n = nameOf(k) + suffix; rows.push(`val ${n} = ${kColor(v)}`); map.push([`--${k}`, n, v, label]);
  }
  return rows.join('\n');
};
const extra = Object.entries(appVars).filter(([k, v]) => isHex(v) && !/^(md-|t-)/.test(k));
const colorKt = `package ${pkg}.presentation.utils.theme

import androidx.compose.ui.graphics.Color

// Generated by android-design/scripts/handoff/team-theme.mjs from the HTML flow's tokens.css (+ app.css).
// Names match the CSS variables (--md-primary → MdPrimary, --x-field-1 → Field1) so a flow and its code read the same;
// the Md prefix keeps role tokens clear of Material names (Surface, Error).
// Feature code imports these tokens; never Color(0x…) / Color.White literals outside this file.

${colorLines(light, '', 'Light scheme (tokens.css :root)')}
${Object.keys(dark).length && scheme !== 'light' ? '\n' + colorLines(dark, 'Dark', 'Dark scheme (tokens.css :root[data-theme="dark"])') : ''}
${extra.length ? '\n// App colours (app.css :root)\n' + extra.map(([k, v]) => { const n = nameOf(k); map.push([`--${k}`, n, v, 'app.css']); return `val ${n} = ${kColor(v)}`; }).join('\n') : ''}
`;

// ---------- fonts ----------
const famOf = (v) => (/'([^']+)'/.exec(v || '') || [, 'Roboto'])[1];
const display = famOf(light['font-display']), text = famOf(light['font-text']);
const weightsFor = (fam) => {
  const imp = new RegExp(`family=${fam.replace(/ /g, '\\+')}:[^'"&)]*wght@([\\d;.]+)`).exec(tokens);
  const ws = imp ? imp[1].split(';').map((w) => +w).filter((w) => w >= 100) : [400, 500, 600, 700];
  return [...new Set(ws)].sort((a, b) => a - b);
};
const WN = { 100: 'Thin', 200: 'ExtraLight', 300: 'Light', 400: 'Normal', 500: 'Medium', 600: 'SemiBold', 700: 'Bold', 800: 'ExtraBold', 900: 'Black' };
const WF = { 100: 'thin', 200: 'extralight', 300: 'light', 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold', 800: 'extrabold', 900: 'black' };
const constName = (fam) => fam.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
const resName = (fam, w) => `${fam.toLowerCase().replace(/[^a-z0-9]+/g, '_')}_${WF[w]}`;
const fams = [...new Set([text, display])];
const ttfs = [];
const fontKt = `package ${pkg}.presentation.utils.theme

import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import ${pkg}.R

// .ttf only, in res/font (lowercase snake_case). Generated by team-theme.mjs.
${fams.map((f) => `val ${constName(f)} = FontFamily(\n${weightsFor(f).map((w) => { ttfs.push(`res/font/${resName(f, w)}.ttf`); return `    Font(R.font.${resName(f, w)}, FontWeight.${WN[w]}),`; }).join('\n')}\n)`).join('\n\n')}
`;

// ---------- Typography.kt ----------
const SIZES = [10, 11, 12, 13, 14, 16, 18, 20, 22, 24, 28, 32];
const W = [['EB', 800], ['B', 700], ['SB', 600], ['M', 500], ['R', 400]];
const lh = (s) => Math.max(s + 4, Math.ceil((s * 1.3) / 2) * 2); // real line height: room for stacked Vietnamese diacritics
const availT = weightsFor(text), availD = weightsFor(display);
const tok = (prefix, fam, avail) => SIZES.flatMap((s) => W.filter(([, w]) => avail.includes(w)).map(([k, w]) => `val ${prefix}${s}${k} = appTextStyle(${s}.sp, FontWeight.${WN[w]}, ${constName(fam)})`)).join('\n');
const typoKt = `package ${pkg}.presentation.utils.theme

import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.style.LineHeightStyle
import androidx.compose.ui.unit.TextUnit
import androidx.compose.ui.unit.sp

// Team token grid T{size}{EB|B|SB|M|R}${display !== text ? ' for text and D{size}{…} for the display face' : ''}.
// Unlike the old base (lineHeight = fontSize) every token has a real line height so Vietnamese diacritics never clip.
private fun lineHeightFor(size: Float) = maxOf(size + 4f, kotlin.math.ceil(size * 1.3f / 2f) * 2f)

private fun appTextStyle(fontSize: TextUnit, fontWeight: FontWeight, family: FontFamily = ${constName(text)}) = TextStyle(
    fontFamily = family,
    fontSize = fontSize,
    lineHeight = lineHeightFor(fontSize.value).sp,
    fontWeight = fontWeight,
    letterSpacing = 0.sp,
    lineHeightStyle = LineHeightStyle(LineHeightStyle.Alignment.Center, LineHeightStyle.Trim.None),
)

${tok('T', text, availT)}
${display !== text ? '\n// Display face\n' + tok('D', display, availD) : ''}
`;

// ---------- Dimens.kt ----------
const radii = Object.entries(light).filter(([k]) => /^r-/.test(k)).map(([k, v]) => [pascal(k.slice(2)), parseFloat(v)]);
const dimensKt = `package ${pkg}.presentation.utils.theme

import androidx.compose.ui.unit.dp

/** Spacing scale: padding, margin and gap use only these steps, picked by component (android-design layout.md). */
object Spacing {
    val S8 = 8.dp    // icon ↔ label, between chips, badge inset, vertical padding of pills / rows
    val S12 = 12.dp  // between sibling tiles / cards / buttons, section title → content
    val S16 = 16.dp  // screen margin, card / banner / row padding, bottom bar
    val S24 = 24.dp  // dialog / sheet / empty-block insets, between big groups
}

/** Corner radii from the flow's shape preset. Pills use CircleShape. */
object Radius {
${radii.map(([n, v]) => `    val ${n} = ${v}.dp`).join('\n') || '    val M = 16.dp'}
}
`;

// ---------- Theme.kt ----------
const ROLES = ['primary', 'on-primary', 'primary-container', 'on-primary-container', 'secondary', 'on-secondary', 'secondary-container', 'on-secondary-container',
  'tertiary', 'on-tertiary', 'tertiary-container', 'on-tertiary-container', 'error', 'on-error', 'error-container', 'on-error-container', 'background', 'on-background',
  'surface', 'on-surface', 'surface-variant', 'on-surface-variant', 'outline', 'outline-variant', 'surface-container-lowest', 'surface-container-low',
  'surface-container', 'surface-container-high', 'surface-container-highest'];
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const args = (src, suf) => ROLES.filter((r) => isHex(src['md-' + r] || '')).map((r) => `        ${camel(r)} = Md${pascal(r)}${suf},`).join('\n');
const both = scheme !== 'light' && Object.keys(dark).length;
const themeKt = `package ${pkg}.presentation.utils.theme

import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Typography
${both ? 'import androidx.compose.material3.darkColorScheme\n' : ''}import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable

// The base default scheme. Feature code uses the named tokens (Color.kt / Typography.kt), not MaterialTheme roles.
@Composable
fun ${themeName}(
    darkTheme: Boolean = ${scheme === 'dark' ? 'true, // the design is dark-first' : 'false, // light only, as in the team base'}
    content: @Composable () -> Unit,
) {
    val colorScheme = ${both ? `if (darkTheme) darkColorScheme(\n${args(dark, 'Dark')}\n    ) else ` : ''}lightColorScheme(
${args(light, '')}
    )
    MaterialTheme(colorScheme = colorScheme, typography = Typography(), content = content)
}
`;

// ---------- write ----------
fs.mkdirSync(out, { recursive: true });
const written = [];
const write = (name, body) => {
  const p = path.join(out, name);
  const target = fs.existsSync(p) && !force ? p + '.new' : p;
  fs.writeFileSync(target, body); written.push(path.relative(process.cwd(), target));
};
write('Color.kt', colorKt); write('Font.kt', fontKt); write('Typography.kt', typoKt); write('Dimens.kt', dimensKt); write('Theme.kt', themeKt);
write('token-map.md', `# Token map (flow CSS → Kotlin)\n\nScheme: ${scheme}. Fonts: ${fams.join(', ')} (.ttf files to add: ${ttfs.join(', ')}).\n\n| CSS variable | Kotlin | Value | Source |\n|---|---|---|---|\n${map.map((r) => `| \`${r[0]}\` | \`${r[1]}\` | ${r[2]} | ${r[3]} |`).join('\n')}\n`);
console.log(`team theme (${scheme}) → ${path.relative(process.cwd(), out) || '.'}\n  ${written.join('\n  ')}\nfonts to add (.ttf): ${ttfs.join(', ')}\ncolours: ${map.length} tokens · text styles: T${display !== text ? ' + D' : ''} grid with real line heights`);
